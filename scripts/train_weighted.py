#!/usr/bin/env python3
"""
train_weighted.py - Training script with trajectory quality weighting.

This script extends the standard training to support per-trajectory weights
generated by the tiny scorer system.

Key differences from train.py:
1. Loads trajectory weights from .npz file
2. DataLoader returns (observation, actions, episode_indices)
3. Loss function computes weighted mean instead of simple mean

Usage:
    python scripts/train_weighted.py --config-name pi05_piper \
        --exp_name weighted_exp \
        --weights-path ./trajectory_weights.npz \
        --weight-warmup-steps 1000
"""

